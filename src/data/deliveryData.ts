export function getMonthRecord(restaurant: RestaurantId, month: MonthKey | string): MonthlyRecord {
  const key = (month in MONTH_META ? month : 'ago_2026') as MonthKey;
  if (restaurant === 'dify') return DIFY_DATA.months[key];
  if (restaurant === 'fogo') return FOGO_DATA.months[key];
  return CONSOLIDATED_DATA[key];
}

export function getPreviousMonthKey(month: MonthKey | string): MonthKey | null {
  const key = month as MonthKey;
  return MONTH_META[key]?.prevMonth ?? null;
}

